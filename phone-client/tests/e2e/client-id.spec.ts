import {test,expect} from '@playwright/test'
test('API credentials form accepts App ID and App Secret without Client ID',async({page})=>{
 test.skip(process.env.E2E_CLIENT_ID_FORM!=='1','Explicit UI-only credential validation check; does not contact Telphin or the model.')
 await page.goto('/login')
 await page.getByLabel('Рабочая почта').fill(process.env.E2E_EMAIL!)
 await page.getByLabel('Пароль',{exact:true}).fill(process.env.E2E_PASSWORD!)
 await page.getByRole('button',{name:'Войти',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Обзор звонков'})).toBeVisible()
 await page.goto('/assistant')
 await page.getByRole('button',{name:'Добавить доступы',exact:true}).click()
 const card=page.getByRole('region',{name:'Защищённая форма доступов Телфина'})
 await card.getByLabel('App ID',{exact:true}).fill('ui-only-not-an-actual-app')
 await card.getByLabel('App Secret',{exact:true}).fill('UI_ONLY_NO_PROVIDER_REQUEST')
 const id=card.locator('input[inputmode="numeric"]')
 await expect(id).toHaveValue('')
 expect(await id.evaluate(input=>(input as HTMLInputElement).required)).toBe(false)
 expect(await card.locator('form').evaluate(form=>(form as HTMLFormElement).checkValidity())).toBe(true)
 await page.getByRole('button',{name:'Закрыть форму доступов',exact:true}).click()
 await expect(card).toHaveCount(0)
})
